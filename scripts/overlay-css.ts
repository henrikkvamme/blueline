import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { compile, optimize } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";
import { forShadowRoot } from "./shadow-css.ts";

/*
 * Compiles the tools' CSS (src/overlay.css) for their shadow root, and writes it as a string
 * to src/ui/overlay-css.gen.ts, so an app needs no Tailwind for the tools. `--check` writes
 * nothing, and fails when the file is not current.
 *
 * A shadow root is not a page, so the CSS changes in three ways:
 * - A browser ignores `@property` in a shadow root. Tailwind's own fallback for a browser
 *   without `@property` gives each variable its initial value in the `properties` layer, the
 *   lowest; it is kept for every browser, and the `@property` rules go.
 * - Each `rem` becomes `px` at 16 px, so the page's root font size does not resize the tools.
 * - The theme and the base that Tailwind puts on `:root`, `html` and `:host` go on the tools'
 *   own root elements, which first take back what they inherit from the page.
 */

const ROOT = path.resolve(import.meta.dirname, "..");
const INPUT = path.join(ROOT, "src", "overlay.css");
const OUTPUT = path.join(ROOT, "src", "ui", "overlay-css.gen.ts");

/** Tailwind's CSS for the classes the tools use. */
async function tailwind(): Promise<string> {
  const base = path.dirname(INPUT);
  const compiled = await compile(readFileSync(INPUT, "utf8"), { base, onDependency: () => {} });
  const root =
    compiled.root === "none"
      ? []
      : compiled.root === null
        ? [{ base, pattern: "**/*", negated: false }]
        : [{ ...compiled.root, negated: false }];
  const scanner = new Scanner({ sources: [...root, ...compiled.sources] });
  return compiled.build(scanner.scan());
}

const css = optimize(forShadowRoot(await tailwind()), { minify: true }).code;
const file = `// Generated by scripts/overlay-css.ts from src/overlay.css. Do not edit.\nexport const OVERLAY_CSS = ${JSON.stringify(css)};\n`;

if (process.argv.includes("--check")) {
  const now = readFileSync(OUTPUT, "utf8");
  if (now !== file) {
    console.error("src/ui/overlay-css.gen.ts is not current: run pnpm run css");
    process.exit(1);
  }
} else writeFileSync(OUTPUT, file);
